export const OMAProvider: React.FC<{ children: ReactNode }> = ({ children }) => {
  const [workOrders, setWorkOrders] = usePersistedState<WorkOrder[]>('workOrders', sampleWorkOrders);

  const addWorkOrder = (wo: Omit<WorkOrder, 'id' | 'workOrderNumber' | 'createdDate'>) => {
    setWorkOrders(prev => {
      const newWO: WorkOrder = {
        ...wo,
        id: Date.now().toString(),
        workOrderNumber: genWONumber(prev.length),
        createdDate: new Date().toISOString(),
      };
      return [newWO, ...prev];
    });
  };

  const updateWorkOrder = (id: string, updates: Partial<WorkOrder>) =>
    setWorkOrders(prev => prev.map(w => w.id === id ? { ...w, ...updates } : w));

  const deleteWorkOrder = (id: string) =>
    setWorkOrders(prev => prev.filter(w => w.id !== id));

  const generateFromComponent = (params: {
    componentId: string; aircraftId: string; aircraftModel: string;
    aircraftRegistration: string; aircraftSerialNumber: string;
    ttAc: number; tcAc: number;
    description: string; taskCode: string; projectedDate: string; createdBy: string;
  }) => {
    setWorkOrders(prev => {
      const newWO: WorkOrder = {
        id: Date.now().toString(),
        workOrderNumber: genWONumber(prev.length),
        componentId: params.componentId,
        elaborationDate: new Date().toISOString().split('T')[0],
        projectedDate: params.projectedDate,
        directedTo: '',
        aircraftId: params.aircraftId,
        aircraftModel: params.aircraftModel,
        aircraftRegistration: params.aircraftRegistration,
        aircraftSerialNumber: params.aircraftSerialNumber,
        ttAcCreation: params.ttAc,
        tcAcCreation: params.tcAc,
        componentDesc: params.description,
        componentPN: '',
        componentSN: '',
        tsnTsoCreation: 0,
        csnCsoCreation: 0,
        taskCode: params.taskCode,
        description: params.description,
        generatedBy: params.createdBy,
        type: 'scheduled',
        priority: 'high',
        status: 'pending',
        partsRequired: [],
        partsAvailable: false,
        createdBy: params.createdBy,
        createdDate: new Date().toISOString(),
        autoGenerated: true,
      };
      return [newWO, ...prev];
    });
  };

  return (
    <OMAContext.Provider value={{ workOrders, addWorkOrder, updateWorkOrder, deleteWorkOrder, generateFromComponent }}>
      {children}
    </OMAContext.Provider>
  );
};

export const useOMA = () => {
  const ctx = useContext(OMAContext);
  if (!ctx) throw new Error('useOMA must be used within OMAProvider');
  return ctx;
};
